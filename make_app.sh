#!/bin/bash
# Build "Steezy Studio.app" - the double-clickable launcher.
#
#   ./make_app.sh              -> builds into ~/Applications
#   ./make_app.sh /some/dir    -> builds somewhere else
#
# Same reasons as Beat Thief's make_app.sh: the bundle carries a copy of the
# code and runs from inside itself, because macOS blocks apps from reading the
# Desktop, and it is signed with the local Steezy Studio certificate so rebuilds
# keep one identity. It runs on the shared engine Python (engine/setup.sh).

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEST="${1:-$HOME/Applications}"
APP="$DEST/Steezy Studio.app"

case "$DEST" in
    "$HOME"/Desktop/*|"$HOME"/Documents/*|"$HOME"/Downloads/*)
        echo "Refusing to build into $DEST - macOS blocks apps from reading" >&2
        echo "Desktop, Documents and Downloads, so the app couldn't start." >&2
        exit 1 ;;
esac

# --- the engine: its Python must exist and have the window library
ENGINE="$("$REPO/engine/setup.sh" --path)"
PYTHON="${PYTHON:-$ENGINE/python/bin/python3}"
if ! "$PYTHON" -c 'import sys; assert sys.version_info >= (3, 12)' >/dev/null 2>&1; then
    "$REPO/engine/setup.sh"
fi
# The shared pin set: copied beside the engine so every tool's build can find it.
cp "$REPO/constraints.txt" "$ENGINE/constraints.txt"
"$PYTHON" -m pip install --quiet --prefer-binary --upgrade -c "$ENGINE/constraints.txt" -r "$REPO/requirements.txt"
FFMPEG_DIR="$ENGINE/bin"
ARCH="$("$PYTHON" -c 'import platform; print(platform.machine())')"

# --- signing identity (made once; see make_signing_identity.sh)
# shellcheck source=signing_keychain.sh
. "$REPO/signing_keychain.sh"
"$REPO/make_signing_identity.sh" >/dev/null
open_signing_keychain
IDENTITY="$(signing_identity)"
if [ -z "$IDENTITY" ]; then
    echo "No signing identity found; run ./make_signing_identity.sh" >&2
    exit 1
fi

# A second copy elsewhere is how the Dock goes stale; sweep a stray one.
if [ "$DEST" != "/Applications" ] && [ -e "/Applications/Steezy Studio.app" ]; then
    echo "Removing a stray copy at /Applications/Steezy Studio.app" >&2
    rm -rf "/Applications/Steezy Studio.app"
fi

# Remember which clone this app came from, so the app can update itself from it.
mkdir -p "$(dirname "$ENGINE")" && printf '%s\n' "$REPO" > "$(dirname "$ENGINE")/studio_dir"

mkdir -p "$DEST"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cp -R "$REPO/studio" "$APP/Contents/Resources/studio"
rm -rf "$APP/Contents/Resources/studio/__pycache__"
cp -R "$REPO/ui" "$APP/Contents/Resources/ui"
cp "$REPO/registry.json" "$APP/Contents/Resources/registry.json"

WORK="$(mktemp -d)"
ICONSET="$WORK/icon.iconset"
mkdir -p "$ICONSET"
if "$PYTHON" "$REPO/render_logo.py" "$WORK/master.png" 1024 2>/dev/null; then
    for size in 16 32 128 256 512; do
        sips -z $size $size "$WORK/master.png" --out "$ICONSET/icon_${size}x${size}.png" >/dev/null 2>&1
        sips -z $((size * 2)) $((size * 2)) "$WORK/master.png" --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null 2>&1
    done
    iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/Steezy Studio.icns" 2>/dev/null || true
else
    echo "Warning: could not render the icon; the app will use a generic one." >&2
fi
rm -rf "$WORK"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>
    <string>Steezy Studio</string>
    <key>CFBundleDisplayName</key>
    <string>Steezy Studio</string>
    <key>CFBundleIdentifier</key>
    <string>com.stefan.steezystudio</string>
    <key>CFBundleVersion</key>
    <string>1.0</string>
    <key>CFBundleShortVersionString</key>
    <string>1.0</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleExecutable</key>
    <string>Steezy Studio</string>
    <key>CFBundleIconFile</key>
    <string>Steezy Studio</string>
    <key>LSUIElement</key>
    <false/>
    <key>NSHighResolutionCapable</key>
    <true/>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/Steezy Studio" <<LAUNCHER
#!/bin/bash
# Generated by make_app.sh - edit that, not this.
# Everything is logged, and a failure to start raises a dialog: a launcher that
# silently does nothing is the worst outcome.

LOG="\$HOME/Library/Logs/steezy_studio.log"
mkdir -p "\$(dirname "\$LOG")"
echo "--- \$(date) ---" >> "\$LOG"

export PATH="$FFMPEG_DIR:/opt/homebrew/bin:/usr/local/bin:\$PATH"
export STEEZY_ENGINE_DIR="$ENGINE"

cd "\$(dirname "\$0")/../Resources" || exit 1
/usr/bin/arch -$ARCH "$PYTHON" -u -m studio.gui >> "\$LOG" 2>&1
status=\$?

if [ \$status -ne 0 ]; then
    detail="\$(tail -n 3 "\$LOG" | tr '"' "'")"
    osascript -e "display dialog \"Steezy Studio could not start.

\$detail

Full log: \$LOG\" with title \"Steezy Studio\" buttons {\"OK\"} default button 1 with icon caution" >/dev/null 2>&1
fi
exit \$status
LAUNCHER

chmod +x "$APP/Contents/MacOS/Steezy Studio"
codesign --force --deep --sign "$IDENTITY" "$APP"
codesign --verify --strict "$APP"

echo "Built $APP"
echo "Double-click it, or drag it to your Dock."
